// The window.mc API on top of a transport (1.2.0): the Electron preload (ipcRenderer) and the Tauri bridge
// (src/renderer/src/bridge/mc.ts) build the same object from this one file, so the argument shaping of every method (cuts,
// defaults, wrapping, omitted keys) cannot drift between the two. scripts/gen-ipc-contract.mjs reads this file for the
// channel of each method (src-tauri/gen/ipc-contract.json).
import type { McApi } from './api';
import type { AppPlatform } from '../shared/platform';

/** What a host provides: request/response, fire-and-forget, push events and the synchronous values. */
export interface McTransport {
  invoke(channel: string, ...args: unknown[]): Promise<any>;
  send(channel: string, ...args: unknown[]): void;
  /** Subscribes to a push channel; the returned function unsubscribes (synchronously). */
  on(channel: string, cb: (...args: any[]) => void): () => void;
  platform: AppPlatform;
  windowsBuild: number;
  pathForFile(file: File): string;
}

/** Base64 of bytes (Uint8Array.prototype.toBase64 where the engine has it, else btoa in chunks). */
function base64Of(bytes: Uint8Array): string {
  const native = (bytes as Uint8Array & { toBase64?: () => string }).toBase64;
  if (native) return native.call(bytes);
  let binary = '';
  for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(binary);
}

/**
 * An image preview of 1.2.0 carries the raw bytes (no base64 inside the IPC answer); the page gets the `data:` URL of 1.1.4.
 * The Electron preload answers the string already, so this is a no-op there.
 */
export async function withImageDataUrl<T>(answer: Promise<T>): Promise<T> {
  const preview = await answer;
  const p = preview as { kind?: unknown; mime?: unknown; dataUrl?: unknown } | null;
  if (p?.kind === 'image' && p.dataUrl instanceof Uint8Array) return { ...p, dataUrl: `data:${String(p.mime)};base64,${base64Of(p.dataUrl)}` } as T;
  return preview;
}

