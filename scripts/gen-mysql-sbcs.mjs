// D7: writes src-tauri/crates/unimux-db/src/wire/sbcs_tables.rs, the single-byte tables iconv-lite (the version mysql2
// 3.24 loads) uses for the mysql2 encoding names of MySQL charsets that Node itself does not convert. Each table is the
// UTF-16 unit iconv-lite decodes every byte 0..255 to (U+FFFD where the codepage has no character); the Rust side builds
// the encoder from it the way iconv-lite's SBCSCodec does (the last byte for a unit wins, '?' for the rest).
// Run: node scripts/gen-mysql-sbcs.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(join(dirname(fileURLToPath(import.meta.url)), '..', 'node_modules', 'mysql2', 'index.js'));
const iconv = require('iconv-lite');
const version = require('iconv-lite/package.json').version;

const NAMES = [
  'latin2', 'cp850', 'koi8r', 'cp1251', 'hebrew', 'tis620', 'latin7', 'koi8u', 'greek', 'cp1250', 'cp1257', 'latin5',
  'armscii8', 'cp866', 'macintosh', 'macroman', 'cp852', 'cp1256',
];

const lines = [
  '// Generated by scripts/gen-mysql-sbcs.mjs from iconv-lite ' + version + ' (what mysql2 3.24 uses). Do not edit.',
  '//! Single-byte decode tables of iconv-lite for the mysql2 encoding names (byte -> UTF-16 unit, U+FFFD: no character).',
  '',
  '#[rustfmt::skip]',
  'pub const SBCS: &[(&str, [u16; 256])] = &[',
];
for (const name of NAMES) {
  const codec = iconv.getCodec(name);
  if (codec.constructor.name !== 'SBCSCodec') throw new Error(`${name} is not single-byte`);
  const units = [];
  for (let b = 0; b < 256; b++) {
    const s = iconv.decode(Buffer.from([b]), name);
    if (s.length !== 1) throw new Error(`${name} ${b}: ${JSON.stringify(s)}`);
    units.push('0x' + s.charCodeAt(0).toString(16).padStart(4, '0'));
  }
  lines.push(`    ("${name}", [`);
  for (let i = 0; i < 256; i += 16) lines.push('        ' + units.slice(i, i + 16).join(', ') + ',');
  lines.push('    ]),');
}
lines.push('];', '');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src-tauri', 'crates', 'unimux-db', 'src', 'wire', 'sbcs_tables.rs');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out} (${NAMES.length} tables)`);
